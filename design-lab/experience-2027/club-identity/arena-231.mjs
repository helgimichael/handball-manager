// Arena Nights 231: the authoritative implementation status of every canonical Experience 2027 surface.
// Source of truth: arena-231-status.json (one record per surface ID; status + evidence).
// Reads the canonical lab data (data/surfaces.js) read-only and refuses to run if any surface,
// alternative or recommendation is missing, or if the status file has an unknown or missing ID.
// Writes docs/club-identity/ARENA-NIGHTS-231-TRACEABILITY.csv and ARENA-NIGHTS-231-IMPLEMENTATION-STATUS.md.
// Usage (repo root): node design-lab/experience-2027/club-identity/arena-231.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..", "..");
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(here, "..", "data", "surfaces.js"), "utf8"), ctx);
const surfaces = ctx.window.LAB_DATA.surfaces;
const statusFile = path.join(here, "arena-231-status.json");
const status = JSON.parse(fs.readFileSync(statusFile, "utf8"));

const STATUSES = ["NOT_STARTED", "IN_PROGRESS", "IMPLEMENTED", "VERIFIED", "BLOCKED", "OWNER_DECISION_REQUIRED"];
const PRIORITIES = ["P0", "P1", "P2", "P3"];
const errors = [];
const altCount = surfaces.reduce((n, s) => n + (s.alternatives || []).length, 0);
if (surfaces.length !== 231) errors.push(`expected 231 surfaces, found ${surfaces.length}`);
if (altCount !== 551) errors.push(`expected 551 alternatives, found ${altCount}`);
const ids = new Set(surfaces.map((s) => s.id));
if (ids.size !== surfaces.length) errors.push("duplicate surface IDs in the lab data");
for (const s of surfaces) {
  if (!(s.alternatives || []).some((a) => a.key === s.recommendation)) errors.push(`${s.id}: recommendation ${s.recommendation} has no matching alternative`);
  const r = status[s.id];
  if (!r) { errors.push(`${s.id}: no status record`); continue; }
  if (!STATUSES.includes(r.status)) errors.push(`${s.id}: unknown status ${r.status}`);
  if (r.status === "VERIFIED" && !r.verification) errors.push(`${s.id}: VERIFIED without verification evidence`);
  if ((r.status === "IMPLEMENTED" || r.status === "VERIFIED") && !r.evidence) errors.push(`${s.id}: ${r.status} without file evidence`);
  if ((r.status === "BLOCKED" || r.status === "OWNER_DECISION_REQUIRED") && !r.summary) errors.push(`${s.id}: ${r.status} without a reason`);
}
for (const id of Object.keys(status)) if (!ids.has(id)) errors.push(`status record ${id} is not a canonical surface`);
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

const rows = surfaces.map((s) => {
  const alt = s.alternatives.find((a) => a.key === s.recommendation);
  const r = status[s.id];
  return { id: s.id, domain: s.domain, name: s.name, kind: s.kind, route: s.route, priority: s.priority, rec: `${s.recommendation}: ${alt.name}`, alternatives: s.alternatives.length, dependencies: (s.dependencies || []).join("; "), ...r };
});

const csvCell = (v) => { const t = String(v ?? ""); return /[",\n;]/.test(t) ? `"${t.replace(/"/g, '""')}"` : t; };
const cols = ["id", "domain", "name", "kind", "route", "priority", "rec", "alternatives", "milestone", "status", "summary", "evidence", "verification", "dependencies"];
const csv = [cols.join(","), ...rows.map((r) => cols.map((c) => csvCell(r[c])).join(","))].join("\n") + "\n";

const count = (f) => rows.filter(f).length;
const esc = (t) => String(t ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const complete = count((r) => r.status === "VERIFIED");
const milestones = [...new Set(rows.map((r) => r.milestone))].sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));
const md = `# Arena Nights 231 — Implementation Status

Generated by \`design-lab/experience-2027/club-identity/arena-231.mjs\` from \`arena-231-status.json\` (the single authoritative status source) and the canonical Design Lab data (\`design-lab/experience-2027/data/surfaces.js\`, read only). The generator refuses to run unless all 231 surfaces, all 551 alternatives and every recommendation are present and every surface has exactly one record.

**Complete (VERIFIED): ${complete} / 231.** A surface counts as complete only when VERIFIED. Machine-readable copy: \`ARENA-NIGHTS-231-TRACEABILITY.csv\`.

| Status | All | ${PRIORITIES.join(" | ")} |
|---|---|${PRIORITIES.map(() => "---").join("|")}|
${STATUSES.map((st) => `| ${st} | ${count((r) => r.status === st)} | ${PRIORITIES.map((p) => count((r) => r.status === st && r.priority === p)).join(" | ")} |`).join("\n")}
| **Total** | **${rows.length}** | ${PRIORITIES.map((p) => `**${count((r) => r.priority === p)}**`).join(" | ")} |

## Milestones

| Milestone | Surfaces | VERIFIED | IMPLEMENTED | IN_PROGRESS | NOT_STARTED | BLOCKED / OWNER |
|---|---|---|---|---|---|---|
${milestones.map((m) => { const f = (st) => count((r) => r.milestone === m && st.includes(r.status)); return `| ${m} | ${count((r) => r.milestone === m)} | ${f(["VERIFIED"])} | ${f(["IMPLEMENTED"])} | ${f(["IN_PROGRESS"])} | ${f(["NOT_STARTED"])} | ${f(["BLOCKED", "OWNER_DECISION_REQUIRED"])} |`; }).join("\n")}

## Execution map (all 231 surfaces)

| ID | Surface | Kind | Priority | Selected alternative | Dependencies | Milestone | Status | What is true now | Evidence |
|---|---|---|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.id} | ${esc(r.name)} (\`${esc(r.route)}\`) | ${r.kind} | ${r.priority} | ${esc(r.rec)} | ${esc(r.dependencies)} | ${r.milestone} | **${r.status}** | ${esc(r.summary)} | ${esc([r.evidence, r.verification].filter(Boolean).join(" — "))} |`).join("\n")}
`;

const outDir = path.join(root, "docs", "club-identity");
const targets = [[path.join(outDir, "ARENA-NIGHTS-231-TRACEABILITY.csv"), csv], [path.join(outDir, "ARENA-NIGHTS-231-IMPLEMENTATION-STATUS.md"), md]];
if (process.argv.includes("--check")) {
  const stale = targets.filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== c);
  if (stale.length) { console.error(`out of date: ${stale.map(([f]) => path.basename(f)).join(", ")}`); process.exit(1); }
} else for (const [f, c] of targets) fs.writeFileSync(f, c);
const by = Object.fromEntries(STATUSES.map((st) => [st, count((r) => r.status === st)]));
console.log(JSON.stringify({ surfaces: rows.length, alternatives: altCount, ...by, p0Verified: count((r) => r.priority === "P0" && r.status === "VERIFIED") }));
