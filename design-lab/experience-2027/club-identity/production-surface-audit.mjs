// Club Identity C5: production audit of all 231 Experience 2027 surfaces against the shipped
// Arena Nights integration. Reads the canonical lab data (data/surfaces.js) -- recommendations
// and alternatives are only READ, never changed. Writes docs/club-identity/CLUB-IDENTITY-ARENA-SURFACE-AUDIT.md.
// Usage (repo root): node design-lab/experience-2027/club-identity/production-surface-audit.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..", "..");
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(here, "..", "data", "surfaces.js"), "utf8"), ctx);
const surfaces = ctx.window.LAB_DATA.surfaces;

/** Recommendations whose structure (not only the Arena language) is implemented in production by this work. */
const STRUCTURAL = {
  "ENT-03": "Wizard takes on the chosen club's identity (Arena adaptation 'living club card', CareerEntryFrame clubId)",
  "ENT-03d": "Club cards: club identity, relation label (D7) and verified/fallback colour marker",
  "MDY-01": "Arena adaptation 'intensity escalation': calm preparation -> club neon floods the header on matchday -> glowing live state (.hm-shell[data-game-state])",
  "ENT-07": "Club identity in the shell: active-club neon on badge and active nav, clubless state, relation label (navigation model itself unchanged)",
  "MGR-01c": "Clubless state: orange identity, 'Utan klubb · Tidigare <club>' in shell and header",
};
// Routes the shipped app actually serves (career layout + entry screens). Dynamic segments are matched by prefix.
const SERVED = ["/", "/new-game", "/load-game", "/settings", "/career", "*"];
const served = (route) => SERVED.some((r) => r === "*" ? /^\*|^\/career/.test(route) : route === r || route.startsWith(`${r} `) || route.startsWith(`${r}?`) || route.startsWith(`${r}/`) || route.startsWith("/career/"));

const rows = surfaces.map((s) => {
  const alt = (s.alternatives || []).find((a) => a.key === s.recommendation || a.id === s.recommendation) || {};
  const arena = s.arena?.status || "";
  const internal = arena === "internal";
  const language = internal ? "n/a (internal tool)" : served(s.route) ? "Arena Nights applied" : "route not in production";
  const structure = STRUCTURAL[s.id] ? `IMPLEMENTED -- ${STRUCTURAL[s.id]}` : internal ? "n/a" : arena === "token" ? "Arena-compatible; recommended structure NOT yet implemented" : "Recommended structure NOT yet implemented";
  return { id: s.id, name: s.name, route: s.route, priority: s.priority, rec: `${s.recommendation} ${alt.name || alt.title || ""}`.trim(), arena, language, structure };
});
const count = (f) => rows.filter(f).length;
const esc = (t) => String(t ?? "").replace(/\|/g, "\\|");
let md = `# Club Identity — Arena Nights Production Surface Audit (C5)

Generated by \`design-lab/experience-2027/club-identity/production-surface-audit.mjs\` from the canonical Design Lab data (\`data/surfaces.js\`, ${rows.length} surfaces). Recommendations and alternatives are read only; none was changed.

| Measure | Count |
|---|---|
| Surfaces | ${rows.length} |
| Arena Nights visual language applied in production | ${count((r) => r.language === "Arena Nights applied")} |
| Internal / developer tools (not themed by design) | ${count((r) => r.arena === "internal")} |
| Recommended *structure* implemented by this work | ${count((r) => r.structure.startsWith("IMPLEMENTED"))} |
| Recommended structure still to implement | ${count((r) => r.structure.startsWith("Recommended") || r.structure.startsWith("Arena-compatible"))} |
| Priority P0 still to implement | ${count((r) => r.priority === "P0" && !r.structure.startsWith("IMPLEMENTED") && r.arena !== "internal")} |

**Reading this table.** "Arena Nights applied" means the surface renders in the production Arena theme (night foundation, Arena type, depth, status colours, club-neon accent following the active club), through the global theme layer (it covers every served route). The computed-style sweep (no light paper surfaces, no text below 3:1, no horizontal overflow) was run on 30 routes on desktop and 14 on mobile, including the live match and the match report; routes not swept (e.g. press-conference detail, editor) are themed but not individually verified. It does **not** mean the surface's recommended layout (the alternative chosen in the lab) is built: that is the "Structure" column.

| Id | Surface | Route | Priority | Recommendation | Arena status | Production language | Structure |
|---|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.id} | ${esc(r.name)} | \`${esc(r.route)}\` | ${r.priority} | ${esc(r.rec)} | ${r.arena} | ${r.language} | ${esc(r.structure)} |`).join("\n")}
`;
const out = path.join(root, "docs", "club-identity", "CLUB-IDENTITY-ARENA-SURFACE-AUDIT.md");
fs.writeFileSync(out, md);
console.log(`${rows.length} surfaces -> ${out}`);
