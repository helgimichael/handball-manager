// Screenshots of several club identities (registry-driven) for the audit documentation.
// Usage (repo root, lab served on 127.0.0.1:3790): node design-lab/experience-2027/club-identity/capture-club-boards.cjs
const fs = require('fs');
const path = require('path');
const { chromium } = require(process.env.PW_PATH || 'C:/DEV/PROJECTS/handball-manager/node_modules/playwright');
const here = __dirname;
const OUT = path.resolve(here, '..', '..', '..', 'docs', 'experience-2027', 'boards-clubs');
const BASE = 'http://127.0.0.1:3790/design-lab/experience-2027/';
const reg = JSON.parse(fs.readFileSync(path.join(here, 'registry.json'), 'utf8')).clubs;

const hue = (hex) => { const v = parseInt(hex.slice(1), 16); const r = (v >> 16) / 255, g = ((v >> 8) & 255) / 255, b = (v & 255) / 255; const mx = Math.max(r, g, b), mn = Math.min(r, g, b); if (mx - mn < 0.08) return -1; const d = mx - mn; const h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; return h * 60; };
const pick = (id) => reg.find((c) => c.id === id);
const showcase = [];
const hueDist = (a, b) => { const x = hue(a.neon), y = hue(b.neon); return x < 0 || y < 0 ? (x === y ? 0 : 999) : Math.min(Math.abs(x - y), 360 - Math.abs(x - y)); };
['swe2-tumba', 'se_club_hammarby_if_hf'].forEach((id) => { const c = pick(id); if (c) showcase.push(c); });
// Phase 2: verified Swedish clubs from EVERY division (2 per tier, distinct neons), then 2 international, 1 ice-silver, 1 pending.
const good = (x) => x.status === 'VERIFIED' && !x.fallback && !x.neonRule.startsWith('ice') && x.accentBasis !== 'club-or-away-colour';
for (const [tier, n] of [['SE-1 Handbollsligan', 2], ['SE-2 Allsvenskan', 2], ['SE-3 Division 1', 2], ['SE-4 Division 2', 2], ['International / world pool', 2]]) {
  let k = 0;
  for (const c of reg.filter((x) => x.tier === tier && good(x))) { if (k >= n) break; if (showcase.includes(c) || showcase.some((s2) => s2.tier === tier && hueDist(s2, c) < 22)) continue; showcase.push(c); k++; }
}
const mono = reg.find((c) => c.neonRule.startsWith('ice') && c.tier.startsWith('SE')) || reg.find((c) => c.neonRule.startsWith('ice')); if (mono && !showcase.includes(mono)) showcase.push(mono);
const pend = reg.find((c) => c.fallback && c.tier.startsWith('SE')); if (pend) showcase.push(pend);
const SCREENS = [['dashboard', 'C', 1], ['player', 'C', 1], ['squad', 'A', 0], ['scouting', 'C', 1], ['matchday', 'C', 1], ['analysis', 'C', 1]];

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const b = await chromium.launch();
  const desk = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const mob = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true });
  const shot = async (page, club, k, alt, adapt, file, q = 70) => { const p = new URLSearchParams({ s: k, alt, theme: 'b', nav: 'c', club }); if (adapt) p.set('adapt', '1'); await page.goto(`${BASE}frame.html?boards=club#${p}`); await page.waitForTimeout(500); await page.screenshot({ path: path.join(OUT, file), type: 'jpeg', quality: q }); return file; };
  let md = `# Club identity boards\n\nGenerated by \`club-identity/capture-club-boards.cjs\` from the Club Identity Registry. Every image shows the **retained surface recommendation** in Arena Nights; only the club changes. Showcase (Phase 2): IFK Tumba and Hammarby, then VERIFIED clubs from every Swedish division (Handbollsligan, Allsvenskan, Division 1, Division 2) with distinct neons, two international clubs, one Ice Silver club (black/white shirt) and one club on the orange FALLBACK (kit unknown, marked "Klubbfärg ej verifierad").\n\n`;
  md += `## Full set: six key screens\n\n`;
  for (const c of showcase.slice(0, 4)) {
    const files = [];
    for (const [k, alt, ad] of SCREENS) files.push(await shot(desk, c.id, k, alt, ad, `${c.id}-${k}.jpg`));
    md += `### ${c.name} — home shirt ${c.kit.primary.name || 'unknown'} ${c.kit.primary.hex || ''} → neon \`${c.neon}\` (${c.status})\n\n| Dashboard + nav | Player | Squad |\n|---|---|---|\n| ![](${files[0]}) | ![](${files[1]}) | ![](${files[2]}) |\n| **Scouting** | **Matchday** | **Analysis** |\n| ![](${files[3]}) | ![](${files[4]}) | ![](${files[5]}) |\n\n`;
  }
  md += `## Club by club (dashboard, matchday, mobile player)\n\n| Club | Home shirt → neon | Dashboard | Matchday | Mobile |\n|---|---|---|---|---|\n`;
  for (const c of showcase) {
    const a = await shot(desk, c.id, 'dashboard', 'C', 1, `${c.id}-dash.jpg`);
    const m = await shot(desk, c.id, 'matchday', 'C', 1, `${c.id}-match.jpg`);
    const mm = await shot(mob, c.id, 'player', 'C', 1, `${c.id}-mobile.jpg`, 60);
    md += `| ${c.name}<br>${c.tier} · ${c.status} | ${c.kit.primary.name || '—'} ${c.kit.primary.hex || ''}${c.neonRule !== 'primary' ? ` (${c.neonRule})` : ''} → \`${c.neon}\` | ![](${a}) | ![](${m}) | ![](${mm}) |\n`;
  }
  const cl = await shot(desk, 'none', 'clubless', 'B', 0, 'clubless.jpg');
  const cld = await shot(desk, 'none', 'dashboard', 'C', 1, 'clubless-dash.jpg');
  md += `| Utan klubb (clubless) | — → \`${'#ff7a1a'}\` | ![](${cld}) | ![](${cl}) | |\n`;
  // lab club view
  const lab = await b.newPage({ viewport: { width: 1600, height: 1100 } });
  await lab.goto(BASE + 'index.html?boards=club');
  await lab.evaluate((id) => localStorage.setItem('hm-exp27-lab-v1', JSON.stringify({ amend20261113: true, view: 'clubid', identity: 'b', club: 'swe2-tumba', clubPick: id })), showcase[1] ? showcase[1].id : 'swe2-tumba');
  await lab.reload(); await lab.waitForSelector('.ci-card'); await lab.waitForTimeout(2500);
  await lab.screenshot({ path: path.join(OUT, 'lab-club-identity-view.jpg'), type: 'jpeg', quality: 70 });
  md += `\n## Design Lab: Club identity view\n\n![](lab-club-identity-view.jpg)\n`;
  fs.writeFileSync(path.join(OUT, 'README.md'), md);
  await b.close();
  console.log('showcase:', showcase.map((c) => `${c.name} ${c.neon}`).join(' | '));
})().catch((e) => { console.error(e); process.exit(1); });
