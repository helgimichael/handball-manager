// Captures the owner direction (Arena Nights + Club Identity System + retained recommendations).
// Usage (repo root, lab served on 127.0.0.1:3790): node design-lab/experience-2027/capture-arena-boards.cjs
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { chromium } = require(process.env.PW_PATH || 'C:/DEV/PROJECTS/handball-manager/node_modules/playwright');
const BASE = 'http://127.0.0.1:3790/design-lab/experience-2027/frame.html?boards=arena';
const OUT = path.resolve(__dirname, '..', '..', 'docs', 'experience-2027', 'boards-arena');
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, 'data', 'surfaces.js'), 'utf8'), ctx);
const S = ctx.window.LAB_DATA.surfaces;
const shots = [];
const seen = new Set();
for (const s of S.filter((x) => x.protoKey)) {
  if (seen.has(s.protoKey)) continue; seen.add(s.protoKey);
  shots.push({ key: s.protoKey, id: s.id, alt: s.recommendation, adapt: s.arena.status === 'adapt', name: s.name, altName: (s.alternatives.find((a) => a.key === s.recommendation) || {}).name, arena: s.arena });
}
shots.push({ key: 'clubless', id: 'MGR-01c', alt: 'B', adapt: false, name: 'Clubless manager', altName: 'Job market (Arena-native)', arena: { status: 'native' } });

(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const b = await chromium.launch();
  const desk = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const mob = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true });
  let md = '# Owner direction boards — Arena Nights + Club Identity System\n\nEach row is a hi-fi surface showing its **retained recommendation** in Arena Nights (adapted where the register lists a conflict) with the Week Spine + hub-rail navigation recommended for ENT-07/08. Columns: IFK Tumba (neon blue), Hammarby (neon green), clubless (neon orange) at 1440×900, plus Tumba on mobile 390×844. Generated by `design-lab/experience-2027/capture-arena-boards.cjs`.\n\n';
  for (const sh of shots) {
    const files = [];
    for (const club of ['tum', 'ham', 'none']) {
      const p = new URLSearchParams({ s: sh.key, alt: sh.alt, theme: 'b', nav: 'c', club });
      if (sh.adapt) p.set('adapt', '1');
      await desk.goto(`${BASE}#${p}`); await desk.waitForTimeout(600);
      const f = `${sh.key}-${club}-desktop.jpg`; await desk.screenshot({ path: path.join(OUT, f), type: 'jpeg', quality: 70 }); files.push(f);
    }
    const p = new URLSearchParams({ s: sh.key, alt: sh.alt, theme: 'b', nav: 'c', club: 'tum' }); if (sh.adapt) p.set('adapt', '1');
    await mob.goto(`${BASE}#${p}`); await mob.waitForTimeout(450);
    const fm = `${sh.key}-tum-mobile.jpg`; await mob.screenshot({ path: path.join(OUT, fm), type: 'jpeg', quality: 60 }); files.push(fm);
    md += `## ${sh.id} · ${sh.name}\n\nRecommended (retained): **${sh.alt} · ${sh.altName}** · Arena: ${sh.arena.status}${sh.arena.adaptedName && sh.adapt ? ` → *${sh.arena.adaptedName}*` : ''}\n\n| IFK Tumba | Hammarby | Clubless | Mobile (Tumba) |\n|---|---|---|---|\n| ${files.map((f) => `![${f}](${f})`).join(' | ')} |\n\n`;
  }
  fs.writeFileSync(path.join(OUT, 'README.md'), md);
  await b.close();
  console.log(`captured ${shots.length * 4} images to ${OUT}`);
})().catch((e) => { console.error(e); process.exit(1); });
