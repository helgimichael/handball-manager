// HM-ALPHA2-01: regenerates lib/game-data/realLeagueSchedules.ts from the
// committed Profixio snapshot. Fails (writes nothing) if any league is not
// a complete, valid double round-robin of its canonical clubs.
//   npx tsx scripts/generate-real-league-schedules.ts
import fs from "node:fs";
import { getClubsByCompetition } from "../lib/game-data/clubs";
import { parseProfixioScheduleSnapshot, PROFIXIO_SCHEDULE_LEAGUES, validateRealLeagueSchedule } from "../lib/gameWorld/profixioSchedule";

const SNAPSHOT = "data/real-world/sweden/2026-27/fixtures/profixio-schedules-2026-10-31.psv";
const OUT = new URL("../lib/game-data/realLeagueSchedules.ts", import.meta.url);

const snapshot = fs.readFileSync(new URL(`../../../${SNAPSHOT}`, import.meta.url), "utf8");
const parsed = parseProfixioScheduleSnapshot(snapshot);

const blocks: string[] = [];
for (const league of PROFIXIO_SCHEDULE_LEAGUES) {
  const fixtures = parsed[league.competitionId] ?? [];
  const problems = validateRealLeagueSchedule(fixtures, getClubsByCompetition(league.competitionId).map((c) => c.id));
  if (problems.length) throw new Error(`${league.competitionId}: ${problems.join("; ")}`);
  const rows = fixtures.map((f) => `    { id: "${f.id}", profixioMatchId: "${f.profixioMatchId}", round: ${f.round}, date: "${f.date}", kickoffTime: "${f.kickoffTime}", homeClubId: "${f.homeClubId}", awayClubId: "${f.awayClubId}" },`);
  blocks.push(`  "${league.competitionId}": {\n    season: "2026/27",\n    source: "${league.scheduleUrl}",\n    fixtures: [\n${rows.map((r) => `  ${r}`).join("\n")}\n    ],\n  },`);
  console.log(`${league.competitionId}: ${fixtures.length} fixtures, ${fixtures[0].date} .. ${fixtures.at(-1)!.date}`);
}

fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/generate-real-league-schedules.ts -- do not edit.
// HM-ALPHA2-01: real 2026/27 regular-season schedules (Profixio, retrieved
// 2026-10-31; ${SNAPSHOT}).
// Local Europe/Stockholm dates and kickoff times; fixture ids are the
// original Profixio match ids. No real-world results are imported.
import type { RealLeagueFixture } from "../gameWorld/profixioSchedule";

export type RealLeagueSchedule = { season: string; source: string; fixtures: readonly RealLeagueFixture[] };

export const REAL_LEAGUE_SCHEDULES: Readonly<Record<string, RealLeagueSchedule>> = {
${blocks.join("\n")}
};

export function getRealLeagueSchedule(competitionId: string): RealLeagueSchedule | undefined {
  return REAL_LEAGUE_SCHEDULES[competitionId];
}
`,
);
