// Club Identity C5: generates the production club visual identity table from
// the ONE source of club colour truth, the Club Identity Registry
// (design-lab/experience-2027/club-identity/registry.json). Nothing here
// chooses a colour: neon, rule and status are copied; kit/crest swatches use
// the registry's documented reference hue (neonRef ?? paletteHex ?? hex).
// Usage (apps/game): node scripts/generate-club-visual-identity.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const registryPath = fileURLToPath(new URL("../../../design-lab/experience-2027/club-identity/registry.json", import.meta.url));
const outPath = fileURLToPath(new URL("../lib/game-data/clubVisualIdentity.data.ts", import.meta.url));
const registry = JSON.parse(readFileSync(registryPath, "utf8"));

const swatch = (c) => (c && (c.neonRef || c.paletteHex || c.hex)) ? String(c.neonRef || c.paletteHex || c.hex).toLowerCase() : null;
const rule = (r) => r.startsWith("ice-silver") ? "ICE_SILVER" : r.startsWith("fallback") ? "FALLBACK" : "CLUB";

const rows = registry.clubs.map((c) => {
  const unknown = c.status === "UNKNOWN" || c.status === "NOT_RESEARCHED" || c.status === "RETIRED";
  const kit = unknown || !c.kit || !swatch(c.kit.primary) ? null : { primary: swatch(c.kit.primary), secondary: swatch(c.kit.secondary) };
  const crest = c.crest && swatch(c.crest.primary) ? { primary: swatch(c.crest.primary), secondary: swatch(c.crest.secondary) } : null;
  return [c.id, { status: c.status, rule: rule(c.neonRule), neon: c.neon.toLowerCase(), kit, crest, season: c.kit?.season ?? null }];
});

const body = `// GENERATED by apps/game/scripts/generate-club-visual-identity.mjs from
// design-lab/experience-2027/club-identity/registry.json (${registry.clubs.length} clubs). Do not edit:
// change the registry (research, overrides) and regenerate. A test fails if this file is stale.
import type { ClubVisualRecord } from "./clubVisualIdentity";

export const CLUB_VISUAL_PALETTE = ${JSON.stringify({ clubless: registry.clubless.toLowerCase(), iceSilver: registry.monochrome.toLowerCase(), pending: registry.pending.toLowerCase() })} as const;

export const CLUB_VISUAL_RECORDS: Readonly<Record<string, ClubVisualRecord>> = {
${rows.map(([id, r]) => `  ${JSON.stringify(id)}: ${JSON.stringify(r)},`).join("\n")}
};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outPath, "utf8").replace(/\r\n/g, "\n");
  if (current !== body) { console.error("clubVisualIdentity.data.ts is stale: run node scripts/generate-club-visual-identity.mjs"); process.exit(1); }
  console.log("clubVisualIdentity.data.ts is up to date");
} else {
  writeFileSync(outPath, body);
  console.log(`${rows.length} club visual records -> ${outPath}`);
}
