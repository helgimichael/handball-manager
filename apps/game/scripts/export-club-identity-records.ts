// Club Identity C5: exports the canonical identity fields of every club record
// (game-data CLUBS, identity overlay merged) for the Club Identity Registry
// build. The registry COPIES these fields; it never edits them by hand
// (FINAL-DECISIONS §3.4). Usage (apps/game): node --import tsx scripts/export-club-identity-records.ts
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { CLUBS, canonicalClubId, clubRelationForSeason, clubRelationLabel, clubTeamType, parentClubOf } from "../lib/game-data";

const out = fileURLToPath(new URL("../../../design-lab/experience-2027/club-identity/clubs-identity.json", import.meta.url));
const records = CLUBS.map((c) => {
  const relation = clubRelationForSeason(c.id);
  return {
    id: c.id,
    canonicalId: canonicalClubId(c.id),
    status: c.status ?? "active",
    addedInWorld: c.addedInWorld ?? null,
    retiredReason: c.retiredReason ?? null,
    teamType: clubTeamType(c.id),
    relation: relation ? { kind: relation.relation, parentClubId: relation.parentClubId, confidence: relation.relationConfidence } : null,
    parentClubId: parentClubOf(c.id) ?? null,
    relationLabel: clubRelationLabel(c.id) ?? null,
    historicalNames: c.historicalNames ?? [],
  };
});
writeFileSync(out, JSON.stringify({ note: "generated by apps/game/scripts/export-club-identity-records.ts -- do not edit", clubs: records }, null, 1) + "\n");
console.log(`${records.length} club identity records -> ${out}`);
