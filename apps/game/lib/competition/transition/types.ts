/** Read-only planning contracts. Deliberately no CareerState, strength or CA/PA inputs. */
export type Evidence = { readonly url: string; readonly section: string; readonly seasonId?: string; readonly verifiedOn?: string; readonly documentDate?: string; readonly verification?: 'VERIFIED' | 'UNVERIFIED' };
export type FamilyDefinition = {
  readonly id: string;
  readonly nation: string;
  readonly category: string;
  readonly tier: number;
  readonly boundary: boolean;
};
export type LeagueDefinition = {
  readonly id: string;
  readonly familyId: string;
  readonly size: number;
  readonly legs: number;
};
export type EntrySelector =
  | { readonly kind: "RANK"; readonly competitionId: string; readonly rank: number }
  | { readonly kind: "EXTERNAL"; readonly slotId: string; readonly familyId: string };
export type EntryRule = {
  readonly id: string;
  readonly selector: EntrySelector;
  readonly purpose: "DIRECT" | "RETAIN" | "QUALIFY";
  readonly targetFamilyId: string;
  readonly eligibility: boolean;
  readonly replacement: "NONE" | "UPPER_HALF";
  readonly source: Evidence;
};
export type StageEntrant =
  | { readonly kind: "ENTRY"; readonly entryId: string }
  | { readonly kind: "WINNER"; readonly stageId: string };
export type QualificationStage = {
  readonly id: string;
  readonly entrants: readonly [StageEntrant, StageEntrant];
  readonly format: "BEST_OF_3" | "BEST_OF_5" | "TWO_LEG";
  /** Entrant index at home in each game. Null means M1.2A did not verify home priority. */
  readonly homeOrder: readonly (0 | 1)[] | null;
  /** Re-orient homeOrder toward the actual better source-table finisher after replacements. Equal ranks need a ruling. */
  readonly homeReference?: "BETTER_SOURCE_RANK";
  /** Explicit game-policy draw only when replacements leave equal source ranks. */
  readonly equalRankHomeOrder?: readonly (0 | 1)[];
  /** Official permitted game windows. Missing dates block scheduling, not sporting result inspection. */
  readonly gameWindows?: readonly { readonly startDate: string; readonly endDate: string; readonly source: Evidence }[];
  readonly terminalDecider?: { readonly kind: 'SEVEN_METRES_AFTER_TWO_OVERTIMES'; readonly source: Evidence };
  readonly winnerFamilyId?: string;
  readonly loserFamilyId?: string;
  readonly source: Evidence;
};
export type CompetitionRules = {
  readonly provenance?: 'OFFICIAL' | 'GAME_CONTINUITY';
  readonly boundaryLeagues?: readonly { readonly id: string; readonly familyId: string }[];
  readonly id: string;
  readonly seasonId: string;
  readonly nextSeasonId: string;
  readonly verifiedOn: string;
  readonly families: readonly FamilyDefinition[];
  readonly leagues: readonly LeagueDefinition[];
  readonly entries: readonly EntryRule[];
  /** Topological order; forward references/cycles are rejected. */
  readonly stages: readonly QualificationStage[];
  readonly points: { readonly win: number; readonly draw: number; readonly loss: number };
  readonly ranking: "POINTS_GD_GF_MUTUAL_NEUTRAL";
  readonly rankingSource: Evidence;
  readonly limitations: readonly { readonly code: string; readonly message: string; readonly source: Evidence }[];
};
export type CanonicalClub = { readonly id: string; readonly nation: string; readonly category: string };
export type Standing = {
  readonly clubId: string;
  readonly played: number;
  readonly won: number;
  readonly drawn: number;
  readonly lost: number;
  readonly goalsFor: number;
  readonly goalsAgainst: number;
  readonly goalDifference: number;
  readonly points: number;
};
export type MutualResult = {
  readonly homeClubId: string;
  readonly awayClubId: string;
  readonly homeGoals: number;
  readonly awayGoals: number;
};
export type RankingDecision = {
  readonly kind: "NEUTRAL_MATCH" | "ORGANIZER_RULING";
  readonly orderedClubIds: readonly string[];
  readonly evidence: string;
};
export type LeagueTableInput = {
  readonly competitionId: string;
  readonly seasonId: string;
  readonly completed: boolean;
  readonly rows: readonly Standing[];
  readonly mutualResults?: readonly MutualResult[];
  readonly rankingDecisions?: readonly RankingDecision[];
};
export type EligibilityDecision = {
  readonly clubId: string;
  readonly targetFamilyId: string;
  readonly seasonId: string;
  readonly status: "ELIGIBLE" | "INELIGIBLE" | "UNKNOWN";
  /** Attests entry acceptance, licence and dated cooperation restrictions; never inferred from ratings. */
  readonly evidence: string;
};
export type KnownQualificationResult = {
  readonly stageId: string;
  readonly seasonId: string;
  readonly participants: readonly [string, string];
  readonly winnerClubId: string;
  /** Concluded result supplied by caller, not a score generated by this planner. */
  readonly origin: "CAREER_SIMULATED" | "OFFICIAL_IMPORTED" | "ADMINISTRATIVE_DECISION";
  readonly evidence: string;
};
/** Supplied fixture evidence. Missing result means unplayed; goals include played extra time, not shoot-out throws. */
export type QualificationFixture = {
  readonly id: string;
  readonly stageId: string;
  readonly seasonId: string;
  readonly game: number;
  readonly homeClubId: string;
  readonly awayClubId: string;
  readonly result?: {
    readonly homeGoals: number;
    readonly awayGoals: number;
    readonly origin: KnownQualificationResult["origin"];
    readonly evidence: string;
    /** Observed terminal decision, not a request to simulate one. */
    readonly decider?: { readonly winnerClubId: string; readonly evidence: string };
  };
};
export type ExternalEntrant = { readonly slotId: string; readonly clubId: string; readonly evidence: string };
export type GroupAllocation = { readonly clubId: string; readonly competitionId: string; readonly evidence: string };
export type PlannerInput = {
  readonly seasonId: string;
  readonly rules: CompetitionRules;
  readonly clubs: readonly CanonicalClub[];
  readonly standings: readonly LeagueTableInput[];
  readonly qualificationResults?: readonly KnownQualificationResult[];
  readonly qualificationFixtures?: readonly QualificationFixture[];
  readonly eligibility?: readonly EligibilityDecision[];
  readonly externalEntrants?: readonly ExternalEntrant[];
  readonly groupAllocations?: readonly GroupAllocation[];
};
export type Dependency = {
  readonly code: string;
  readonly ref: string;
  readonly status: "BLOCKED" | "UNRESOLVED";
  readonly message: string;
};
export type RankGroup = {
  readonly ranks: readonly number[];
  /** Alphabetical for presentation only when rank is unresolved. */
  readonly clubIds: readonly string[];
  readonly reason?: "MISSING_MUTUAL_RESULTS" | "NEUTRAL_MATCH_REQUIRED" | "MULTIWAY_RULING_REQUIRED";
};
export type EntrySelection = {
  readonly entryId: string;
  readonly status: "CONFIRMED" | "UNRESOLVED" | "SUPERSEDED";
  readonly clubIds: readonly string[];
  readonly skippedClubIds: readonly string[];
  readonly supersededBy?: readonly string[];
};
export type MovementClaim = {
  readonly clubId: string;
  readonly fromCompetitionId?: string;
  readonly fromFamilyId: string;
  readonly toFamilyId: string;
  readonly toCompetitionId?: string;
  readonly kind: "PROMOTION" | "RELEGATION" | "REMAIN";
  readonly via: string;
  readonly source: Evidence;
};
export type StageProposal = {
  readonly stageId: string;
  readonly status: "CONFIRMED" | "UNRESOLVED" | "BLOCKED";
  readonly participants: readonly (string | null)[];
  readonly winnerClubId?: string;
  readonly loserClubId?: string;
  readonly resultEvidence?: string;
  readonly resolutionMethod?: "FIXTURES" | "RECORDED_RESULT";
  readonly completedFixtureIds?: readonly string[];
  readonly seriesWins?: Readonly<Record<string, number>>;
  readonly format: QualificationStage["format"];
  readonly source: Evidence;
  /** Potential games, not scheduled fixtures. No dates or results are invented. */
  readonly unresolvedFixtures: readonly {
    readonly game: number;
    readonly homeClubId: string | null;
    readonly awayClubId: string | null;
    readonly conditional: boolean;
  }[];
};
export type TransitionProposal = {
  readonly ruleId: string;
  readonly seasonId: string;
  readonly nextSeasonId: string;
  readonly status: "READY" | "UNRESOLVED" | "BLOCKED";
  readonly rankings: readonly { readonly competitionId: string; readonly groups: readonly RankGroup[] }[];
  readonly entries: readonly EntrySelection[];
  readonly directPromotions: readonly MovementClaim[];
  readonly directRelegations: readonly MovementClaim[];
  readonly qualificationMovements: readonly MovementClaim[];
  readonly remaining: readonly MovementClaim[];
  /** Exactly one disposition per known participant, including explicit unresolved ones. */
  readonly clubs: readonly { readonly clubId: string; readonly status: "CONFIRMED" | "UNRESOLVED" | "BLOCKED"; readonly via: readonly string[] }[];
  readonly qualification: readonly StageProposal[];
  readonly sizes: readonly { readonly scopeId: string; readonly expected: number; readonly confirmed: number; readonly status: "VALID" | "UNRESOLVED" | "BLOCKED" }[];
  readonly dependencies: readonly Dependency[];
};
